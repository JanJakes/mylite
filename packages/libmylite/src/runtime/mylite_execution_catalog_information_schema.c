static bool catalog_text_equals_ascii_case_insensitive(const char *left, const char *right) {
    if (left == NULL || right == NULL) {
        return left == right;
    }
    while (*left != '\0' && *right != '\0') {
        if (catalog_ascii_lower(*left) != catalog_ascii_lower(*right)) {
            return false;
        }
        ++left;
        ++right;
    }
    return *left == '\0' && *right == '\0';
}

static char catalog_ascii_lower(char byte) {
    if (byte >= 'A' && byte <= 'Z') {
        return (char)(byte - 'A' + 'a');
    }
    return byte;
}

size_t mylite_execution_catalog_keyword_count(void) {
    return sizeof(information_schema_keywords) / sizeof(information_schema_keywords[0]);
}

const struct mylite_execution_catalog_keyword *mylite_execution_catalog_keyword_at(size_t index) {
    if (index >= mylite_execution_catalog_keyword_count()) {
        return NULL;
    }
    return &information_schema_keywords[index];
}

size_t mylite_execution_catalog_information_schema_table_definition_count(void) {
    return sizeof(information_schema_table_definitions) /
           sizeof(information_schema_table_definitions[0]);
}

const struct mylite_execution_catalog_table_definition *mylite_execution_catalog_information_schema_table_definition_at(
    size_t index
) {
    if (index >= mylite_execution_catalog_information_schema_table_definition_count()) {
        return NULL;
    }
    return &information_schema_table_definitions[index];
}

const struct mylite_execution_catalog_table_definition *mylite_execution_catalog_information_schema_table_definition_by_name(
    const char *table_name
) {
    if (table_name == NULL) {
        return NULL;
    }
    for (size_t index = 0U;
         index < mylite_execution_catalog_information_schema_table_definition_count();
         ++index) {
        if (catalog_text_equals_ascii_case_insensitive(
                information_schema_table_definitions[index].name,
                table_name
            )) {
            return &information_schema_table_definitions[index];
        }
    }
    return NULL;
}
